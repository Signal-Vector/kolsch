"""`platform.yaml` loading and first-run defaults.

Asset Management is the platform-bootstrap module: no other module
reads `platform.yaml` directly. This file provides:

- Default generation for first-run (no file present).
- YAML load plus structural validation (the top level must be a
  mapping).
- A section-dict accessor consumed by every subsystem at its own
  initialisation.

The exact per-section shape is owned by the consuming subsystem; this
loader only validates that each declared section is a mapping and
exposes it as a dict. `hooks` (spec-131) is the one exception: it is a
*list* of rules rather than a mapping, and — because no consuming
subsystem exists yet to own its shape (dispatch lands in later
spec-131 steps) — this loader eagerly validates each entry against
`schemas.config.HookRule` via `parse_hooks_section`, failing fast at
load time on a malformed rule.
"""

from __future__ import annotations

import contextlib
import fcntl
import logging
import time
from typing import TYPE_CHECKING, Any

from pydantic import ValidationError as _PydanticValidationError

from assets.default_rules import fail_closed_default_rules
from errors import AuthzRulesPersistFailed, ConfigInvalid
from kolsch._yamlio import YAMLError, dump, load, load_with_positions
from schemas import HookRule

if TYPE_CHECKING:
    from collections.abc import Iterator
    from pathlib import Path

_log = logging.getLogger("assets")

# Valid section names. The accessor is permissive — unknown sections
# raise ``KeyError`` rather than a PlatformError.
_KNOWN_SECTIONS: frozenset[str] = frozenset(
    {
        "secrets",
        "sandbox",
        "authorization",
        "storage",
        "event_bus",
        "file_access",
        "defaults",
        "logging",
        # LLM provider configuration.
        "llm_providers",
        "model_aliases",
        # Optional multi-line text describing the workspace's purpose.
        # Surfaced in agent prompts via `{{ workspace.summary }}` and
        # `{{ platform.workspace_summary }}`.
        "workspace_summary",
        # Meta-agent settings. The only knob today is
        # ``target_bundle: <name>`` controlling which bundle the
        # ``author_workflow`` agent writes new files into. When the
        # key is absent, the agent's skill resolves the target to the
        # workspace's first non-``kolsch`` bundle (the primary user
        # bundle); if only ``kolsch`` exists, the agent escalates to
        # the author. No default is written at setup time — leaving
        # the section absent IS the documented "auto-resolve" mode.
        "author_workflow",
        # Context-compaction subsystem (feat-054). Shape:
        # ``{variant, trigger_at, config}``. No default is written at
        # setup time — leaving the section absent IS the documented
        # "off" mode; the provider factory returns ``None`` and the
        # engine skips the trigger check entirely.
        "compaction",
        # Workflow subsystem defaults. Currently one knob:
        # ``default_timeout_seconds`` — how long the blocking
        # ``run_workflow`` (and per-workflow virtual variants) waits
        # for a terminal phase before returning ``phase="running"``.
        # Section absent → hardcoded 300s default preserved.
        "workflows",
        # Shell-command event hooks (spec-131). A list of
        # ``{event, matcher?, command, timeout_seconds?}`` rules — see
        # ``schemas.config.HookRule``. No default is written at setup
        # time — leaving the section absent IS the documented "zero
        # hooks, zero overhead" mode; nothing fires unless the operator
        # opts in explicitly. Unlike every other known section this one
        # is a *list*, not a mapping — see the carve-out in
        # ``_validate_section_shape`` (same shape as
        # ``workspace_summary``'s string carve-out). Loaded once at
        # process start and deliberately excluded from ``/reload``
        # (spec-131 Step 7) — a hook's `command` is an arbitrary shell
        # string, so config-in-the-loop hot-reload is a wider trust
        # boundary than the other sections here.
        "hooks",
    }
)


# Leading comment block of an auto-generated `platform.yaml`. Comment
# lines only, so the parsed mapping is the payload unchanged.
_GENERATED_HEADER = (
    "# Auto-generated by kolsch because no platform.yaml was found.\n"
    "# Authorization is fail-closed: agents may run; every tool is denied.\n"
    "# Run `kolsch setup` to create a full workspace (its default rules\n"
    "# allow or prompt for the builtin tools), or add rules with\n"
    "# `kolsch permissions add`.\n"
)


def default_platform_payload() -> dict[str, Any]:
    """Return the first-run default `platform.yaml` payload.

    The defaults require zero external services: SQLite + in-process
    bus + dotenv secrets + native sandbox + fail-closed rule-based
    authorization.
    File-access defaults allow `data/`, `bundles/`, `sessions/`,
    `content/`, `logs/`, and `platform.yaml`; they deny `.env` and
    `.platform/`.

    Authorization is
    [`fail_closed_default_rules`][assets.default_rules.fail_closed_default_rules]:
    the `agent.execute.*` pre-flight allow, then the protected
    default-deny tail. Agents may run; every tool is denied, in chat
    too (the tail matches before the approval prompt). The set is
    catalog-independent, so it compiles on a root with no bundles.
    `kolsch setup` writes the full workspace rule set instead.
    """
    return {
        "secrets": {"variant": "dotenv", "config": {"path": ".env"}},
        "sandbox": {"variant": "native", "config": {}},
        "authorization": {
            "variant": "rule_based",
            "config": {"rules": fail_closed_default_rules()},
        },
        "storage": {
            "entity_backend": "sqlite",
            "entity_path": ".platform/entities.db",
        },
        "event_bus": {"backend": "in_process"},
        "file_access": {
            # `.` resolves to the workspace root and lets `list_files(path=".")`
            # answer "what's in my workspace?" — per `qol-workspace-root-listable.md`.
            # Without it, default-deny fires on the natural workspace inspection;
            # the fallback to `bash ls -la` only works because bash is broader.
            "allowed_paths": [
                ".",
                "data/",
                "bundles/",
                "sessions/",
                "content/",
                "logs/",
                "platform.yaml",
            ],
            "denied_paths": [".env", ".platform/"],
        },
        "defaults": {
            # No "model" key here on purpose: this payload is what
            # `load_or_create` persists to disk before `kolsch setup`
            # Step D ever runs (and is reachable directly whenever
            # anything boots the platform on a fresh root outside the
            # setup flow). A placeholder provider/model pair here
            # would silently pin an unusable connector; an agent that
            # omits its own `model:` field and finds no
            # `defaults.model` instead fails fast with a clear
            # "field required" validation error at Layer 1 — see
            # `schemas.config.ResolvedAgentConfig.model`. `kolsch
            # setup` always writes a real (possibly mock) value here
            # via `_write_defaults_model` before the starter agent
            # runs.
            "memory": {
                "variant": "recent_buffer",
                "config": {"recent_turns": 20, "max_tokens": 4000},
            },
        },
    }


def load_or_create(root: Path) -> dict[str, Any]:
    """Return the parsed `platform.yaml`, generating defaults on first run.

    Args:
        root: The platform root.

    Returns:
        The parsed top-level mapping. When the file was absent at
        call time, the defaults are written to disk and returned.

    Raises:
        ConfigInvalid: The file is present but malformed.
    """
    path = root / "platform.yaml"
    if not path.exists():
        payload = default_platform_payload()
        _write_yaml(path, payload, header=_GENERATED_HEADER)
        _log.warning(
            "Generated default platform.yaml at %s. Its authorization is "
            "fail-closed: agents may run; every tool is denied. Run "
            "`kolsch setup` to create a full workspace.",
            path,
        )
        return payload

    return _load_existing(path)


def _load_existing(path: Path) -> dict[str, Any]:
    try:
        payload = load(path.read_text(encoding="utf-8"))
    except YAMLError as exc:
        raise ConfigInvalid(
            validation_errors=[
                {
                    "layer": 1,
                    "source": "platform.yaml",
                    "path": "/",
                    "code": "yaml_parse_error",
                    "message": str(exc),
                }
            ],
            where="assets.bootstrap.load_platform_yaml",
        ) from exc

    if payload is None:
        # Empty file → treat as "use defaults" (every section absent).
        return {}
    if not isinstance(payload, dict):
        raise ConfigInvalid(
            validation_errors=[
                {
                    "layer": 1,
                    "source": "platform.yaml",
                    "path": "/",
                    "code": "not_a_mapping",
                    "message": (
                        f"platform.yaml top-level must be a mapping; "
                        f"got {type(payload).__name__}"
                    ),
                }
            ],
            where="assets.bootstrap.load_platform_yaml",
        )

    _validate_section_shape(payload)
    return payload


def _validate_section_shape(payload: dict[str, Any]) -> None:
    """Validate that each declared section is a mapping.

    Two exceptions: `workspace_summary` is a string, and `hooks` is a
    list (`model_aliases` is a flat alias-to-ref string map, which
    still satisfies the mapping check).
    """
    errors: list[dict[str, Any]] = []
    for key, value in payload.items():
        # workspace_summary is a string, not a mapping. Skip the
        # shape check; downstream consumers treat any non-string as
        # None.
        if key == "workspace_summary":
            continue
        if key == "hooks":
            # hooks is a list of rule mappings, not a mapping itself —
            # validated element-by-element below, not here.
            continue
        if not isinstance(value, dict):
            errors.append(
                {
                    "layer": 1,
                    "source": "platform.yaml",
                    "path": f"/{key}",
                    "code": "not_a_mapping",
                    "message": (
                        f"section {key!r} must be a mapping; got {type(value).__name__}"
                    ),
                }
            )
    if errors:
        raise ConfigInvalid(
            validation_errors=errors,
            where="assets.bootstrap.load_platform_yaml",
        )
    if "hooks" in payload:
        parse_hooks_section(payload["hooks"])


def parse_hooks_section(raw: Any) -> list[HookRule]:  # noqa: ANN401 — unvalidated YAML input
    """Validate and parse `platform.yaml`'s `hooks:` section.

    Absent `hooks:` key → callers pass `[]` (not called at all, since
    `_validate_section_shape` only invokes this when the key is
    present) — see `default_platform_payload`'s "absent = off"
    convention, matched here for `hooks`.

    Args:
        raw: The raw value of `payload["hooks"]` — expected to be a
            list of rule mappings matching `HookRule`'s shape
            (`event`, optional `matcher`, `command`, optional
            `timeout_seconds`).

    Returns:
        The validated `HookRule` objects, in file order.

    Raises:
        ConfigInvalid: `raw` is not a list, an entry is not a mapping,
            a required field (`event`/`command`) is missing, an entry
            carries an unknown key, or a field fails its own
            validation (e.g. `timeout_seconds` over the ceiling).
    """
    if not isinstance(raw, list):
        raise ConfigInvalid(
            validation_errors=[
                {
                    "layer": 1,
                    "source": "platform.yaml",
                    "path": "/hooks",
                    "code": "not_a_list",
                    "message": (
                        f"section 'hooks' must be a list; got {type(raw).__name__}"
                    ),
                }
            ],
            where="assets.bootstrap.load_platform_yaml",
        )

    rules: list[HookRule] = []
    errors: list[dict[str, Any]] = []
    for index, entry in enumerate(raw):
        try:
            rules.append(HookRule.model_validate(entry))
        except _PydanticValidationError as exc:
            errors.append(
                {
                    "layer": 1,
                    "source": "platform.yaml",
                    "path": f"/hooks/{index}",
                    "code": "hook_rule_invalid",
                    "message": f"hooks[{index}] is invalid: {exc}",
                }
            )
    if errors:
        raise ConfigInvalid(
            validation_errors=errors,
            where="assets.bootstrap.load_platform_yaml",
        )
    return rules


def _write_yaml(path: Path, payload: dict[str, Any], *, header: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + dump(payload), encoding="utf-8")


# bug-162 — poll interval for `platform_yaml_lock`'s bounded wait.
_LOCK_POLL_INTERVAL_S = 0.05


def platform_yaml_lock_path(root: Path) -> Path:
    """Return the sidecar lock path guarding `root/platform.yaml` rule writes.

    Lives under `.platform/` (agent-denied by the default
    `file_access.denied_paths`) rather than beside `platform.yaml`.
    """
    return root / ".platform" / "platform.yaml.lock"


@contextlib.contextmanager
def platform_yaml_lock(root: Path, *, timeout_s: float = 5.0) -> Iterator[None]:
    """Hold an exclusive `flock` on `root/.platform/platform.yaml.lock`.

    Every kolsch writer of an existing `platform.yaml` runs its read →
    modify → write under this lock: single rule edits through
    `cli.permissions.mutate_platform_rules`, and whole-document rewrites
    (setup's migrations and `defaults.model` / `file_access` updates,
    sync's tool-ref rewrite, `kolsch connect` / `disconnect` /
    `refresh`) through `cli._platform_yaml_write.rewrite_platform_yaml_locked`
    (bug-146). So two kolsch processes (a chat and a `kolsch
    permissions` or `kolsch setup` in another terminal, or two chats)
    can never lose each other's edits. (Creating a missing file, in
    `load_or_create` and setup's fresh install, takes no lock.)

    Polls `LOCK_EX | LOCK_NB` every ~50 ms for up to `timeout_s`, then
    raises. Mirrors the event store's sidecar-lock pattern
    (`store.jsonl.lock_path`); POSIX-only, as the store already is.

    **Advisory.** Only writers that take this lock are serialized: a
    hand editor or an agent's `write_file` that replaces the file
    between a writer's read and its rename can still be lost.

    **Never nest it in one process.** `flock` locks belong to the open
    file description, so a second acquire from the same process opens
    a new description and waits on the first — a nested acquire
    self-deadlocks until `timeout_s` and then raises `lock_timeout`.

    Raises:
        AuthzRulesPersistFailed: `reason="lock_timeout"` when the lock
            is still held after `timeout_s`; `reason="write_failed"`
            when the lock file can't be created or locked.
    """
    lock = platform_yaml_lock_path(root)
    yaml_path = str(root / "platform.yaml")
    try:
        lock.parent.mkdir(parents=True, exist_ok=True)
        handle = lock.open("ab")
    except OSError as exc:
        raise AuthzRulesPersistFailed(
            path=yaml_path,
            reason="write_failed",
            detail=f"cannot open rules lock {lock}: {exc}",
            where="assets.platform_config.platform_yaml_lock",
        ) from exc
    # Closing the handle releases the lock.
    with handle:
        deadline = time.monotonic() + timeout_s
        while True:
            try:
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    raise AuthzRulesPersistFailed(
                        path=yaml_path,
                        reason="lock_timeout",
                        detail=(
                            f"another writer held {lock} for more than {timeout_s:g}s"
                        ),
                        where="assets.platform_config.platform_yaml_lock",
                    ) from None
                time.sleep(_LOCK_POLL_INTERVAL_S)
            except OSError as exc:
                raise AuthzRulesPersistFailed(
                    path=yaml_path,
                    reason="write_failed",
                    detail=f"cannot lock {lock}: {exc}",
                    where="assets.platform_config.platform_yaml_lock",
                ) from exc
        yield


def is_known_section(name: str) -> bool:
    """Return `True` when `name` is one of the documented sections."""
    return name in _KNOWN_SECTIONS


def authorization_rule_source_map(  # noqa: PLR0911 — one early-return per graceful-fallback path (§Design)
    root: Path, *, list_key: str = "rules"
) -> dict[int, tuple[str, int]]:
    """Return `{rule_index: (source_file, source_line)}` for the platform's rules.

    Re-reads `platform.yaml` via `load_with_positions` and walks the
    `authorization.config.<list_key>` list (`rules` by default;
    `locked_rules` for the locked platform rules), recording each
    rule's YAML line (1-indexed) alongside the absolute source path.

    feat-041 uses this to tag every rule the
    `RuleBasedAuthorizationProvider` compiles so `/why` +
    `ToolCallBlock` inline hint can display a `platform.yaml:47`
    breadcrumb pointing at the deny rule's authoring site.

    Returns an empty map when:

    - `platform.yaml` is absent (first-run defaults are used).
    - The `authorization` section is missing or malformed.
    - `load_with_positions` raises a `ConstructorError` because a
      custom `!tag` type is present (fallback path — spec §Design).

    Never raises: the caller uses the empty-map fallback (rules
    compile with `source_file=None`, hint degrades to
    `(unknown source)`).
    """
    from ruamel.yaml.constructor import ConstructorError  # noqa: PLC0415

    path = root / "platform.yaml"
    if not path.exists():
        return {}
    try:
        payload = load_with_positions(path.read_text(encoding="utf-8"))
    except (YAMLError, ConstructorError):
        return {}
    if not isinstance(payload, dict):
        return {}
    authorization = payload.get("authorization")
    if not isinstance(authorization, dict):
        return {}
    config = authorization.get("config")
    if not isinstance(config, dict):
        return {}
    rules = config.get(list_key)
    if rules is None:
        return {}
    # `rules` is a `CommentedSeq` from ruamel; its `.lc.data` maps
    # `rule_index → (line, col)` (0-indexed). Add 1 for the
    # human-readable form. When `lc` / `lc.data` is missing (a plain
    # list slipped in, or a synthetic fixture), degrade gracefully.
    lc = getattr(rules, "lc", None)
    data = getattr(lc, "data", None) if lc is not None else None
    if not isinstance(data, dict):
        return {}
    source_map: dict[int, tuple[str, int]] = {}
    source_str = str(path.resolve())
    for rule_index, position in data.items():
        if not isinstance(rule_index, int):
            continue
        # ruamel's `.lc.data[i]` shape is `(line, col)` for sequences
        # or `(key_line, key_col, val_line, val_col)` for maps. Rules
        # are mappings inside a sequence, but the sequence itself
        # tracks the item's start; take element 0 regardless.
        line_0 = position[0] if position else None
        if not isinstance(line_0, int):
            continue
        source_map[rule_index] = (source_str, line_0 + 1)
    return source_map
